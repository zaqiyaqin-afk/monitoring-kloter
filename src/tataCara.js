const ATURAN = [
  [/badal/i, 'badal'],
  [/^(ihram umrah|niat umrah|miqat)$/i, 'ihramUmrah'],
  [/thawaf umrah|^tawaf$/i, 'thawafUmrah'],
  [/^sa'?i/i, 'sai'],
  [/tahallul umrah|^tahallul$/i, 'tahallulUmrah'],
  [/tahallul awwal/i, 'tahallulAwwal'],
  [/tahallul tsani/i, 'tahallulTsani'],
  [/^tarwiyah$|non tarwiyah/i, 'tarwiyah'],
  [/niat haji|ihram haji|^ihram$/i, 'ihramHaji'],
  [/wukuf/i, 'wukuf'],
  [/murur|muzdalifah/i, 'muzdalifah'],
  [/jumro?a?h aqo?a?bah$/i, 'jumrohAqobah'],
  [/jumro?a?h (ula|wustho|aqo?a?bah) \d+/i, 'jumroh3'],
  [/mabit|tanazul/i, 'mabitMina'],
  [/nafar/i, 'nafar'],
  [/ifadzoh|ifadhah/i, 'ifadzoh'],
  [/wada/i, 'wada'],
  [/raudh?oh|raudhah/i, 'raudhoh']
];

export function tataCaraUntuk(nama) {
  const n = String(nama || '').trim();
  const a = ATURAN.find(([re]) => re.test(n));
  return a ? T[a[1]] : null;
}
